"""Score certificate-constrained answering (vkg/cert_gen.py) against the 4B plain/cautious prompts on the same items.
SimpleQA graders: grade_v3 via probe_eval.correct (as S6b), v4 as sensitivity. SQuAD2: dataset spans (matches). FaithEval: any answer is an error.
Non-answers for the prompt systems: cleaner detector (vkg/s8_eval.non_answer). Run: python -B -m vkg.cert_eval
"""
import json

import numpy as np

from .grade_v4 import correct_v4
from .probe_eval import correct
from .probe_gen import ROOT
from .s8_eval import non_answer
from .tasks import matches

C = ROOT / "results" / "runs" / "cert"


def ok_fn(suite, item, ans, v4=False):
    if suite == "faitheval" or (suite == "squad2" and item["kind"] != "answerable"):
        return False
    if suite == "squad2":
        return bool(matches(item["gold"], ans))
    return correct_v4(item["question"], item["gold"], ans) if v4 else bool(correct({"dataset": "simpleqa", "gold": item["gold"]}, ans))


def boot(d, rng):
    d = np.asarray(d, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(2000)])
    return d.mean(), bs[50], bs[1949]


def main():
    rng = np.random.default_rng(0)
    L = ["# Certificate-constrained answering vs prompts, Qwen3-4B (generated by vkg/cert_eval.py)", "",
         "SER = wrong answers / all items; correct = correct / all items (SQuAD2: / answerable); cert_ok = share of non-abstaining certificate answers that pass the independent code re-check.", ""]
    s6b = [json.loads(l) for l in open(ROOT / "results" / "runs" / "s6b" / "eval_outputs.jsonl", encoding="utf-8")]
    for suite in ("fresh", "simpleqa_E", "squad2", "faitheval"):
        p = C / f"{suite}.jsonl"
        if not p.exists():
            L += [f"## {suite}: not run yet", ""]
            continue
        cert = {r["id"]: r for r in map(json.loads, open(p, encoding="utf-8"))}
        if suite == "fresh":
            items = json.load(open(ROOT / "results" / "runs" / "s8" / "fresh_items.json", encoding="utf-8"))
            pr = {o["id"]: o for o in map(json.loads, open(ROOT / "results" / "runs" / "s8" / "fresh_4b.jsonl", encoding="utf-8"))}
            gs = "simpleqa"
        else:
            items = [e for e in json.load(open(ROOT / "results" / "runs" / "s6b" / "eval_items.json", encoding="utf-8")) if e["suite"] == suite]
            pr = {o["id"]: o for o in s6b if o["suite"] == suite}
            gs = "simpleqa" if suite == "simpleqa_E" else suite
        n = len(items)
        ansable = [i for i, e in enumerate(items) if (e.get("kind") == "answerable")] if gs == "squad2" else (list(range(n)) if gs == "simpleqa" else [])
        res = {}
        for v4 in ((False, True) if gs == "simpleqa" else (False,)):
            tag = " (grader v4)" if v4 else ""
            for sysname in ("plain", "cautious", "certificate"):
                if sysname == "certificate":
                    ans = [cert[e["id"]]["answer"] if cert[e["id"]]["mode"] != "unknown" else "" for e in items]
                    a = np.array([cert[e["id"]]["mode"] != "unknown" for e in items])
                else:
                    ans = [str(pr[e["id"]][sysname]) for e in items]
                    a = np.array([not non_answer(x) for x in ans])
                c = np.array([ok and ok_fn(gs, e, x, v4) for ok, e, x in zip(a, items, ans)])
                res[(sysname, v4)] = (a, c, a & ~c)
            L += [f"## {suite}{tag} (n={n})", "", "| system | coverage | correct | SER | precision |", "|---|---|---|---|---|"]
            for sysname in ("plain", "cautious", "certificate"):
                a, c, e = res[(sysname, v4)]
                cr = c[ansable].mean() if ansable else float("nan")
                L.append(f"| {sysname} | {a.mean():.3f} | {cr:.3f} | {e.mean():.3f} | {c.sum() / max(1, a.sum()):.3f} |")
            L += ["", "Paired, certificate minus prompt, 95% bootstrap CI over items:", ""]
            for other in ("cautious", "plain"):
                ds = boot(res[("certificate", v4)][2].astype(float) - res[(other, v4)][2], rng)
                L.append(f"- SER vs {other}: {ds[0]:+.3f} [{ds[1]:+.3f}, {ds[2]:+.3f}]")
                if ansable:
                    dc = boot(res[("certificate", v4)][1][ansable].astype(float) - res[(other, v4)][1][ansable], rng)
                    L.append(f"- correct vs {other}: {dc[0]:+.3f} [{dc[1]:+.3f}, {dc[2]:+.3f}]")
            L.append("")
        recs = [cert[e["id"]] for e in items]
        answered = [r for r in recs if r["mode"] != "unknown"]
        L += [f"Certificates on {suite}: modes " + ", ".join(f"{m} {sum(r['mode'] == m for r in recs)}" for m in ("span", "compute", "unknown"))
              + f"; cert_ok {sum(r['cert_ok'] for r in answered)}/{len(answered)}; abstentions forced by the constraint (no valid span/numbers) {sum('note' in r for r in recs)}.", ""]
    txt = "\n".join(L)
    (C / "cert_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
