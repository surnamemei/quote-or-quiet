"""Score grader 6 on the blind set V3 (docs/GRADER6_PROTOCOL.md, K1-K3). Run: python -B -m vkg.grader6_eval -> results/grader6/grader6_tables.md"""
import json
from collections import Counter

from .grade6 import veto
from .grade_v4 import correct_v4
from .grader5_eval import cp
from .probe_gen import ROOT

D = ROOT / "results" / "grader6"


def main():
    J = {(r["question"], r["gold"], r["answer"]): r["grade"] for r in map(json.loads, open(ROOT / "results" / "grader5" / "judge_grades.jsonl", encoding="utf-8"))}
    rows = [json.loads(l) for l in open(D / "v3_blind.jsonl", encoding="utf-8")]
    lab = {int(x.split("\t")[0]): x.split("\t")[1] for x in open(D / "v3_labels.txt", encoding="utf-8")}
    key = {u["k"]: u for u in json.load(open(D / "v3_key_HIDDEN.json", encoding="utf-8"))}
    for r in rows:
        r["label"] = lab[r["k"]]
        r["stratum"] = "grader-correct" if key[r["k"]]["grader_correct"] else ("wrong-closed" if key[r["k"]]["files"] == ["closed"] else "wrong-grounded")
        r["judge"] = J[(r["question"], r["gold"], r["answer"])]
        r["veto"] = veto(r["question"], r["gold"], r["answer"]) if r["judge"] == "CORRECT" else None
    G = {"v3 (frozen)": lambda r: key[r["k"]]["grader_correct"],
         "v4": lambda r: correct_v4(r["question"], [r["gold"]], r["answer"]),
         "judge (grader 5)": lambda r: r["judge"] == "CORRECT",
         "grader 6": lambda r: r["judge"] == "CORRECT" and not r["veto"]}
    hw = [r for r in rows if r["label"] != "C"]
    hc = [r for r in rows if r["label"] == "C"]
    L = ["# Grader 6 on the blind set V3 (generated by vkg/grader6_eval.py)", "",
         f"Labels: {dict(Counter(r['label'] for r in rows))}; strata: {dict(Counter(r['stratum'] for r in rows))}", "",
         "| grader | false credit (W/N graded correct) | misses (C not graded correct) |", "|---|---|---|"]
    for n, f in G.items():
        L.append(f"| {n} | {cp(sum(bool(f(r)) for r in hw), len(hw))} | {cp(sum(not f(r) for r in hc), len(hc))} |")
    L += ["", "False credit by stratum (grader 6 / judge):", ""]
    for s in ("wrong-grounded", "wrong-closed", "grader-correct"):
        w = [r for r in hw if r["stratum"] == s]
        c = [r for r in hc if r["stratum"] == s]
        if w:
            L.append(f"- {s}: W/N rows {len(w)}, grader 6 credits {sum(G['grader 6'](r) for r in w)}, judge credits {sum(G['judge (grader 5)'](r) for r in w)}; C rows {len(c)}, grader 6 misses {sum(not G['grader 6'](r) for r in c)}")
        else:
            L.append(f"- {s}: W/N rows 0; C rows {len(c)}, grader 6 misses {sum(not G['grader 6'](r) for r in c)}")
    L += ["", "Vetoes fired (rule, label):", ""]
    L.append("- " + ", ".join(f"{k}: {v}" for k, v in sorted(Counter((r["veto"], r["label"]) for r in rows if r["veto"]).items())))
    L += ["", "Grader 6 disagreements with the label:", ""]
    for r in rows:
        if G["grader 6"](r) != (r["label"] == "C"):
            L.append(f"- k={r['k']} [{r['stratum']}] label {r['label']} judge {r['judge']} veto {r['veto']}: Q: {r['question'][:90]} | gold: {r['gold'][:60]} | answer: {str(r['answer'])[:80]}")
    txt = "\n".join(L)
    (D / "grader6_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
