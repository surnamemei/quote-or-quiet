"""Does the rented pod's judge give the same labels as the local judge?
Same GGUF (SHA-256 2de73110...), same Ollama version (0.34.4), same model IDs (e0a7cdbef002, ac6da0dfba84); the backend differs
(pod: CUDA on RTX PRO 6000; local: Vulkan), so labels may differ by numerics. Re-judges a random sample (seed 0) of the stored
judge labels in results/grader5/judge_grades.jsonl through the pod, bypassing the response cache, and reports agreement.
Run (with an SSH tunnel localhost:11435 -> pod 127.0.0.1:11434):
  OLLAMA_HOST_URL=http://localhost:11435 python -B -m vkg.pod_judge_check [n]  -> results/audit2/pod_judge_check.md"""
import json
import random
import sys
import tempfile
from pathlib import Path

from . import llm
from .grade_judge import judge
from .probe_gen import ROOT

OUT = ROOT / "results" / "audit2"


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    rows = [json.loads(l) for l in open(ROOT / "results" / "grader5" / "judge_grades.jsonl", encoding="utf-8")]
    sample = random.Random(0).sample(rows, min(n, len(rows)))
    llm.CACHE_DIR = Path(tempfile.mkdtemp(prefix="podjudge_"))     # fresh cache: every call really goes to the pod
    assert "11434" not in llm.HOST, "point OLLAMA_HOST_URL at the pod tunnel"
    out, diff = [], []
    for r in sample:
        g = judge(r["question"], r["gold"], r["answer"])
        out.append({**r, "pod_grade": g})
        if g != r["grade"]:
            diff.append(out[-1])
    agree = 1 - len(diff) / len(out)
    with open(OUT / "pod_judge_check.jsonl", "w", encoding="utf-8") as f:
        for o in out:
            f.write(json.dumps(o, ensure_ascii=False) + "\n")
    L = [f"# Pod judge vs local judge (generated by vkg/pod_judge_check.py)", "",
         f"Sample: {len(out)} of {len(rows)} stored judge labels (random, seed 0). Pod host via {llm.HOST}; cache bypassed.", "",
         f"Agreement: {len(out) - len(diff)}/{len(out)} = {agree:.1%}", "", "Disagreements (local -> pod):", ""]
    L += [f"- {d['grade']} -> {d['pod_grade']}: Q: {d['question'][:90]} | gold: {d['gold'][:50]} | answer: {d['answer'][:60]}" for d in diff]
    (OUT / "pod_judge_check.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
