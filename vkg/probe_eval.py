"""S5 step 2: linear probes on hidden states vs controls. Run inside venv_gpu after vkg.probe_gen (trained and --random-init).
python -B -m vkg.probe_eval results/runs/s5
Labels (from the SAME model's own outputs):  A = greedy answer correct;  B = known = at least 1 of 9 answers (greedy + 8 samples) correct.
Train = first 1500 TriviaQA questions; in-distribution test = last 500 TriviaQA; OOD test = the 500 SimpleQA Verified pool questions.
Layer and regularisation are chosen by cross-validation INSIDE the training set only.
Controls: TF-IDF of the question, probe on a random-initialised copy of the model, shuffled training labels; reference signals: sampling agreement and mean log-prob.
"""
import json
import random
import re
import sys
from pathlib import Path

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold
from sklearn.preprocessing import StandardScaler

from .grade_open import grade_v3
from .tasks import matches, norm

ROOT = Path(__file__).resolve().parent.parent
CS = [1e-4, 1e-3, 1e-2, 1e-1, 1.0]


def trivia_ok(ans, aliases):
    if not ans.strip() or len(ans.split()) > 12:
        return False
    na = norm(ans)
    for al in aliases:
        n = norm(al)
        if n and (na == n or (len(n) >= 3 and matches([al], ans))):
            return True
    return False


def correct(rec, ans):
    if rec["dataset"] == "trivia":
        return trivia_ok(ans, rec["gold"])
    return grade_v3({"gold": rec["gold"], "status": "answer", "answer": ans}) == "correct"


def auc(y, s):
    y = np.asarray(y)
    return roc_auc_score(y, s) if 0 < y.sum() < len(y) else float("nan")


def boot(y, scores_list, n=2000, seed=0):
    """Bootstrap over questions; returns per-score (mean, lo, hi) and paired differences to the first score."""
    rng = np.random.default_rng(seed)
    y = np.asarray(y)
    N = len(y)
    draws = []
    for _ in range(n):
        i = rng.integers(0, N, N)
        if 0 < y[i].sum() < N:
            draws.append([roc_auc_score(y[i], np.asarray(s)[i]) for s in scores_list])
    d = np.asarray(draws)
    res = [(auc(y, s), np.percentile(d[:, k], 2.5), np.percentile(d[:, k], 97.5)) for k, s in enumerate(scores_list)]
    diffs = [(np.mean(d[:, 0] - d[:, k]), np.percentile(d[:, 0] - d[:, k], 2.5), np.percentile(d[:, 0] - d[:, k], 97.5)) for k in range(1, len(scores_list))]
    return res, diffs


def cv_pick(X, y, seed=0):
    """Inner 5-fold CV on the training set: best C by mean AUROC. Returns (best_auc, best_C)."""
    skf = StratifiedKFold(5, shuffle=True, random_state=seed)
    best = (-1, None)
    for C in CS:
        sc = []
        for tr, va in skf.split(X, y):
            ss = StandardScaler().fit(X[tr])
            m = LogisticRegression(C=C, class_weight="balanced", max_iter=2000).fit(ss.transform(X[tr]), y[tr])
            sc.append(auc(y[va], m.decision_function(ss.transform(X[va]))))
        if np.nanmean(sc) > best[0]:
            best = (float(np.nanmean(sc)), C)
    return best


def fit_layers(F, y, tr):
    """For each layer: CV on train, pick best layer; fit on all train. Returns (layer_index, C, scaler, model, per-layer CV table)."""
    table = []
    for j in range(F.shape[1]):
        a, C = cv_pick(F[tr, j].astype(np.float32), y[tr])
        table.append((j, a, C))
    j, a, C = max(table, key=lambda t: t[1])
    ss = StandardScaler().fit(F[tr, j].astype(np.float32))
    m = LogisticRegression(C=C, class_weight="balanced", max_iter=2000).fit(ss.transform(F[tr, j].astype(np.float32)), y[tr])
    return j, C, ss, m, table


def score_layers(F, j, ss, m, idx):
    return m.decision_function(ss.transform(F[idx, j].astype(np.float32)))


def main(d):
    d = ROOT / d
    gen = [json.loads(l) for l in open(d / "gen.jsonl", encoding="utf-8")]
    Ft = np.load(d / "feats_trained.npy")
    Fr = np.load(d / "feats_random.npy") if (d / "feats_random.npy").exists() else None
    meta = json.load(open(d / "meta_trained.json"))
    layers = meta["layers"]
    N = len(gen)
    yA = np.array([correct(r, r["greedy_answer"]) for r in gen], dtype=int)
    yB = np.array([any(correct(r, a) for a in [r["greedy_answer"]] + r["samples"]) for r in gen], dtype=int)
    ds = np.array([r["dataset"] for r in gen])
    tri = np.where(ds == "trivia")[0]
    tr, te = tri[:1500], tri[1500:]
    ood = np.where(ds == "simpleqa")[0]
    def agree(r):
        g = norm(r["greedy_answer"])
        return sum(norm(a) == g for a in r["samples"]) / 8.0
    sc_agree = np.array([agree(r) for r in gen])
    lp = np.array([r["lp_mean"] for r in gen])
    qtext = [r["question"] for r in gen]
    L = ["# S5: linear probes on hidden states vs controls (generated by vkg/probe_eval.py)", "",
         f"Model: {meta['model']}; layers probed (hidden_states index): {layers}. Train n={len(tr)} (TriviaQA), ID test n={len(te)}, OOD test n={len(ood)} (SimpleQA Verified pool).",
         f"Base rates and positives: A greedy-correct: train {yA[tr].mean():.3f} ({yA[tr].sum()}), ID test {yA[te].mean():.3f} ({yA[te].sum()}), OOD {yA[ood].mean():.3f} ({yA[ood].sum()}); "
         f"B known: train {yB[tr].mean():.3f} ({yB[tr].sum()}), ID test {yB[te].mean():.3f} ({yB[te].sum()}), OOD {yB[ood].mean():.3f} ({yB[ood].sum()}).", ""]
    for lab, y in (("A greedy answer correct", yA), ("B known (>=1 of 9 correct)", yB)):
        L.append(f"## Label {lab}")
        scores = {}
        j, C, ss, m, tab = fit_layers(Ft, y, tr)
        L.append(f"- trained-model probe: best layer by inner CV = hidden_states[{layers[j]}], C={C}; per-layer CV AUROC: " + ", ".join(f"{layers[t[0]]}:{t[1]:.3f}" for t in tab))
        scores["probe"] = {"id": score_layers(Ft, j, ss, m, te), "ood": score_layers(Ft, j, ss, m, ood)}
        # TF-IDF control
        tf = TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True).fit([qtext[i] for i in tr])
        Xtr = tf.transform([qtext[i] for i in tr])
        bestC = max(CS + [10.0, 100.0], key=lambda C_: np.nanmean([auc(y[tr][v], LogisticRegression(C=C_, class_weight="balanced", max_iter=2000).fit(Xtr[t], y[tr][t]).decision_function(Xtr[v]))
                                                              for t, v in StratifiedKFold(5, shuffle=True, random_state=0).split(Xtr, y[tr])]))
        mt = LogisticRegression(C=bestC, class_weight="balanced", max_iter=2000).fit(Xtr, y[tr])
        scores["tfidf"] = {"id": mt.decision_function(tf.transform([qtext[i] for i in te])), "ood": mt.decision_function(tf.transform([qtext[i] for i in ood]))}
        if Fr is not None:
            jr, Cr, ssr, mr, tabr = fit_layers(Fr, y, tr)
            scores["random_init"] = {"id": score_layers(Fr, jr, ssr, mr, te), "ood": score_layers(Fr, jr, ssr, mr, ood)}
            L.append(f"- random-init probe: best layer {layers[jr]}, inner-CV AUROC {max(t[1] for t in tabr):.3f}")
        rng = np.random.default_rng(1)
        ysh = y.copy()
        ysh[tr] = rng.permutation(y[tr])
        js, Cs, sss, ms, tabs = fit_layers(Ft, ysh, tr)
        scores["shuffled_labels"] = {"id": score_layers(Ft, js, sss, ms, te), "ood": score_layers(Ft, js, sss, ms, ood)}
        scores["sampling_agreement"] = {"id": sc_agree[te], "ood": sc_agree[ood]}
        scores["mean_logprob"] = {"id": lp[te], "ood": lp[ood]}
        for part, idx in (("ID test (TriviaQA)", te), ("OOD (SimpleQA Verified pool)", ood)):
            key = "id" if part.startswith("ID") else "ood"
            names = list(scores)
            res, diffs = boot(y[idx], [scores[n][key] for n in names])
            L += ["", f"### {part}: AUROC [95% bootstrap CI]; positives {int(y[idx].sum())} of {len(idx)}", "", "| score | AUROC | probe minus score (paired) |", "|---|---|---|"]
            for k, n in enumerate(names):
                dtxt = "" if k == 0 else f"{diffs[k-1][0]:+.3f} [{diffs[k-1][1]:+.3f}, {diffs[k-1][2]:+.3f}]"
                L.append(f"| {n} | {res[k][0]:.3f} [{res[k][1]:.3f}, {res[k][2]:.3f}] | {dtxt} |")
        L.append("")
    out = d / "S5_probe_tables.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1])
