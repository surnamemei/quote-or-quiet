"""S10: a code-generated reading curriculum aimed at the residual error found in S7b-S9: misreading a passage that contains
the answer (picking a distractor entity/event/date, the wrong stage of a timeline, a partial date) and answering with a
distractor's fact when the asked fact is absent. All facts are fictitious (random names), so labels are exact and the model
cannot answer from memory. Close prior work (distractor-aware fine-tuning): RAFT (2403.10131), PrismRAG (2507.18857),
"The Distracting Effect" (2505.06914); those use LLM-written or edited distractors on real passages, here everything is
generated by code with exact labels and an explicit "unknown" target when the asked fact is missing.
make(n, seed) -> list of {passage, question, target, kind, answerable}."""
import random

SYL = "ka lo ven tar mir os del an ur bel cor dan el fen gar hol is jor kel lan mor nal or per quin ras sol tor ul var wen yor zan".split()
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]
TITLES = ["deputy director", "director", "chief engineer", "senior lecturer", "professor", "dean", "judge", "chief justice",
          "minister of transport", "minister of finance", "ambassador", "editor", "chief editor", "treasurer", "chairman"]
ORGS = ["Institute", "Academy", "High Court", "Ministry", "Society", "Gazette", "University", "Council", "Museum", "Observatory"]
AWARDS = ["Order of Merit", "Silver Medal", "Prize for Science", "Golden Laurel", "Civic Cross", "Founders' Award", "Bronze Star"]
EVENTS = [("a ferry capsized near", "killing"), ("a bus fell into a river near", "killing"), ("a fire broke out in a market in", "killing"),
          ("a bridge collapsed in", "killing"), ("a tractor trolley fell into a pond near", "killing"), ("a train derailed near", "injuring")]
STAGES = [("joined the {o}", "joining"), ("became a full member of the {o}", "becoming a full member"), ("was elected captain of the {o}", "being elected captain"),
          ("was appointed treasurer of the {o}", "being appointed treasurer"), ("left the {o}", "leaving")]
NUMW = {1000: "one thousand", 2000: "two thousand", 3000: "three thousand", 5000: "five thousand", 8000: "eight thousand", 12000: "twelve thousand"}


def word(r, k=2):
    return "".join(r.choice(SYL) for _ in range(k)).capitalize()


def person(r):
    return f"{word(r)} {word(r, 3)}"


def place(r):
    return word(r, r.choice([2, 3]))


def date(r, y0=1850, y1=2015):
    return r.randint(1, 28), r.choice(MONTHS), r.randint(y0, y1)


def fmt(d, style):
    day, mon, yr = d
    return f"{day} {mon} {yr}" if style else f"{mon} {day}, {yr}"


def bio_item(r):
    ppl = [person(r) for _ in range(3)]
    style = r.random() < 0.5
    facts = {}
    sents = []
    for p in ppl:
        d = date(r, 1880, 1975)
        pl = place(r)
        car = r.sample(TITLES, 3)
        orgs = [f"the {place(r)} {r.choice(ORGS)}" for _ in car]
        yrs = sorted(r.sample(range(d[2] + 22, d[2] + 70), 3))
        aw = (r.choice(AWARDS), r.randint(d[2] + 25, d[2] + 75))
        facts[p] = {"born": d, "place": pl, "career": list(zip(car, orgs, yrs)), "award": aw}
        s = [f"{p} was born on {fmt(d, style)} in {pl}."]
        s += [f"In {y}, {p.split()[0]} became {t} of {o}." for t, o, y in zip(car, orgs, yrs)]
        s.append(f"{p.split()[1]} received the {aw[0]} in {aw[1]}.")
        sents.append(s)
    tgt = r.choice(ppl)
    f = facts[tgt]
    kind = r.choice(["born_date", "born_place", "before", "award_year", "award_name", "miss_place", "miss_award", "miss_before"])
    answerable = not kind.startswith("miss")
    if kind == "born_date":
        q, a = f"On what day, month, and year was {tgt} born?", fmt(f["born"], style)
    elif kind == "born_place":
        q, a = f"Where was {tgt} born?", f["place"]
    elif kind == "before":
        (t0, o0, _), (t1, o1, _) = f["career"][1], f["career"][2]
        q, a = f"What position did {tgt} hold immediately before becoming {t1} of {o1}?", f"{t0} of {o0}"
    elif kind == "award_year":
        q, a = f"In what year did {tgt} receive the {f['award'][0]}?", str(f["award"][1])
    elif kind == "award_name":
        q, a = f"Which award did {tgt} receive in {f['award'][1]}?", f["award"][0]
    elif kind == "miss_place":                       # the target's birth sentence is removed; distractors keep theirs
        i = ppl.index(tgt)
        sents[i] = sents[i][1:]
        q, a = f"Where was {tgt} born?", "unknown"
    elif kind == "miss_award":                       # the target's award sentence is removed
        i = ppl.index(tgt)
        sents[i] = sents[i][:-1]
        q, a = f"In what year did {tgt} receive the {f['award'][0]}?", "unknown"
    else:                                            # asked position is the target's first: nothing came before it in the passage
        t0, o0, _ = f["career"][0]
        q, a = f"What position did {tgt} hold immediately before becoming {t0} of {o0}?", "unknown"
    return sents, q, a, "bio_" + kind, answerable


def event_item(r):
    d = date(r, 1950, 2023)
    n = r.choice([2, 3])
    evs = r.sample(EVENTS, n)
    pls = [place(r) for _ in evs]
    nums = r.sample(range(2, 90), n)
    sents = [[f"On {fmt(d, True)}, {e[0]} {pl}, {e[1]} {k} people."] for e, pl, k in zip(evs, pls, nums)]
    sents[1][0] = sents[1][0].replace(f"On {fmt(d, True)}, ", "On the same day, ")
    sents = [[s[0] for s in sents]]                      # one block, so "the same day" always follows the dated sentence
    i = r.randrange(n)
    verb = "were killed" if evs[i][1] == "killing" else "were injured"
    if r.random() < 0.75:
        q, a, kind, ok = f"How many people {verb} when {evs[i][0]} {pls[i]} on {fmt(d, False)}?", str(nums[i]), "event_count", True
    else:
        other = place(r)
        q, a, kind, ok = f"How many people {verb} when {evs[i][0]} {other} on {fmt(d, False)}?", "unknown", "event_miss", False
    return sents, q, a, kind, ok


def stage_item(r):
    p = person(r)
    o = f"{place(r)} {r.choice(['Rowing Club', 'Chess Society', 'Choir', 'Philatelic Society', 'Cricket Club'])}"
    keep = sorted(r.sample(range(len(STAGES)), 4))       # stages stay in their natural order (join ... leave)
    st = [STAGES[i] for i in keep]
    y0 = r.randint(1900, 2000)
    yrs = sorted(r.sample(range(y0, y0 + 30), 4))
    sents = [[f"{p if k == 0 else p.split()[0]} {s[0].format(o=o)} in {y}." for k, (s, y) in enumerate(zip(st, yrs))]]
    if r.random() < 0.75:
        i = r.randrange(4)
        q, a, kind, ok = f"In what year did {p} {st[i][0].format(o=o).replace('was ', 'get ').replace('became', 'become').replace('joined', 'join').replace('left', 'leave')}?", str(yrs[i]), "stage", True
    else:
        rest = [s for s in STAGES if s not in st][0]
        q, a, kind, ok = f"In what year did {p} {rest[0].format(o=o).replace('was ', 'get ').replace('became', 'become').replace('joined', 'join').replace('left', 'leave')}?", "unknown", "stage_miss", False
    return sents, q, a, kind, ok


def count_item(r):
    o = f"the {place(r)} {r.choice(['Temple', 'Fellowship', 'Guild', 'Union'])}"
    ys = sorted(r.sample(range(1940, 2000), 3))
    vals = sorted(r.sample(list(NUMW), 3))
    sents = [[f"Membership of {o} grew to {NUMW[vals[0]]} by {ys[0]}, reached {NUMW[vals[1]]} by {ys[1]}, and stood at {NUMW[vals[2]]} by {ys[2]}."]]
    if r.random() < 0.4:
        p = person(r)
        k = r.randint(3, 9)
        sents.append([f"Its founder, {p}, was born as one of {k} children."])
        return sents, f"How many siblings did {p} have?", str(k - 1), "infer_siblings", True
    if r.random() < 0.8:
        i = r.randrange(3)
        return sents, f"What was the membership of {o} in {ys[i]}?", f"{vals[i]:,}", "count_year", True
    y = r.choice([y for y in range(1940, 2000) if y not in ys])
    return sents, f"What was the membership of {o} in {y}?", "unknown", "count_miss", False


FILLER = ["The region is known for its rivers and old stone bridges.", "Local newspapers covered the story for several weeks.",
          "Records from this period are kept in the municipal archive.", "The town later built a small museum about its history.",
          "Several of these accounts were collected in a local almanac."]


def make(n, seed):
    r = random.Random(seed)
    gens = [bio_item] * 4 + [event_item] * 2 + [stage_item] * 2 + [count_item] * 2
    out = []
    for _ in range(n):
        sents, q, a, kind, ok = r.choice(gens)(r)
        blocks = [" ".join(s) for s in sents]
        r.shuffle(blocks)
        if r.random() < 0.5:
            blocks.insert(r.randrange(len(blocks) + 1), r.choice(FILLER))
        out.append({"passage": "\n\n".join(blocks), "question": q, "target": a, "kind": kind, "answerable": ok})
    return out
