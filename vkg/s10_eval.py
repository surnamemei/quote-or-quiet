"""Score S10 (docs/S10_PROTOCOL.md, R1-R5). Run after vkg.s10_wait: python -B -m vkg.s10_eval -> results/runs/s10/S10_tables.md
Systems: base plain / cautious (reused outputs), s6b (S6b adapter), s10 (reading-curriculum adapter); all with the code non-answer detector."""
import json
import re

import numpy as np

from .grade6 import veto
from .grade_v4 import correct_v4
from .probe_gen import ROOT
from .s8_eval import non_answer
from .support_check import tokens
from .tasks import matches

R = ROOT / "results" / "runs"
OUT = R / "s10"
J = {(r["question"], r["gold"], r["answer"]): r["grade"] for r in map(json.loads, open(ROOT / "results" / "grader5" / "judge_grades.jsonl", encoding="utf-8"))}


def g6(q, gold, a):
    g = J[(q, gold[0], str(a))]
    return g == "CORRECT" and not veto(q, gold[0], str(a))


def synth_ok(target, a):
    if target == "unknown":
        return False
    ta, aa = tokens(target), tokens(a)
    return ta == aa or (bool(ta) and " ".join(ta) in " ".join(aa) and len(aa) <= len(ta) + 3)


def ok(suite, row, a, grader):
    if suite == "faitheval" or (suite == "squad2" and row["kind"] != "answerable"):
        return False
    if suite == "squad2":
        return bool(matches(row["gold"], a))
    if suite == "synth":
        return synth_ok(row["gold"][0], a)
    return g6(row["question"], row["gold"], a) if grader == "g6" else correct_v4(row["question"], row["gold"], a)


def boot(d, rng):
    d = np.asarray(d, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(2000)])
    return d.mean(), bs[50], bs[1949]


def main():
    rng = np.random.default_rng(0)
    rows = [json.loads(l) for l in open(OUT / "eval_outputs.jsonl", encoding="utf-8")]
    s6b = {(o["suite"], o["id"]): o for o in map(json.loads, open(R / "s6b" / "eval_outputs.jsonl", encoding="utf-8"))}
    f4 = {o["id"]: o for o in map(json.loads, open(R / "s8" / "fresh_4b.jsonl", encoding="utf-8"))}
    for r in rows:                                   # attach reused outputs
        if r["set"] == "dev":
            o = s6b[(r["suite"], r["id"])]
            r["plain"], r["cautious"], r["s6b"] = o["plain"], o["cautious"], o["trained"]
        elif r["set"] == "fresh":
            r["plain"], r["cautious"] = f4[r["id"]]["plain"], f4[r["id"]]["cautious"]
        else:
            r["plain"], r["cautious"] = r.pop("base_plain"), r.pop("base_cautious")
    L = ["# S10: reading curriculum vs S6b (generated by vkg/s10_eval.py)", "",
         "SER = answered and wrong / all; correct = correct / all (SQuAD2: / answerable). SimpleQA graded by grader 6 (v4 in brackets).", ""]
    res = {}
    for suite in ("fresh", "simpleqa_E", "squad2", "faitheval", "synth"):
        sub = [r for r in rows if r["suite"] == suite]
        L += [f"## {suite} (n={len(sub)})", "", "| system | coverage | correct | SER |", "|---|---|---|---|"]
        for s in ("plain", "cautious", "s6b", "s10"):
            a = np.array([not non_answer(r[s]) for r in sub])
            c = np.array([bool(aa) and ok(suite, r, str(r[s]), "g6") for aa, r in zip(a, sub)])
            res[(suite, s)] = (a, c)
            ans = [i for i, r in enumerate(sub) if suite != "squad2" or r["kind"] == "answerable"]
            extra = ""
            if suite in ("fresh", "simpleqa_E"):
                c4 = np.array([bool(aa) and ok(suite, r, str(r[s]), "v4") for aa, r in zip(a, sub)])
                extra = f" (v4 {(a & ~c4).mean():.3f})"
            cr = c[ans].mean() if ans and suite != "faitheval" else float("nan")
            L.append(f"| {s} | {a.mean():.3f} | {cr:.3f} | {(a & ~c).mean():.3f}{extra} |")
        L.append("")
        if suite == "synth":
            L.append("Synthetic test by kind (SER s6b -> s10):")
            for k in sorted({r["kind"] for r in sub}):
                idx = [i for i, r in enumerate(sub) if r["kind"] == k]
                e6 = (res[(suite, "s6b")][0] & ~res[(suite, "s6b")][1])[idx].mean()
                e10 = (res[(suite, "s10")][0] & ~res[(suite, "s10")][1])[idx].mean()
                L.append(f"- {k} (n={len(idx)}): {e6:.2f} -> {e10:.2f}")
            L.append("")
    L += ["## Paired differences, s10 minus s6b (95% bootstrap CI over items)", ""]
    for name, suites in (("FRESH + SimpleQA-E pooled (R2)", ("fresh", "simpleqa_E")), ("FRESH", ("fresh",)), ("SimpleQA-E", ("simpleqa_E",)),
                         ("SQuAD2", ("squad2",)), ("FaithEval", ("faitheval",)), ("synthetic", ("synth",))):
        e10 = np.concatenate([res[(s, "s10")][0] & ~res[(s, "s10")][1] for s in suites])
        e6 = np.concatenate([res[(s, "s6b")][0] & ~res[(s, "s6b")][1] for s in suites])
        c10 = np.concatenate([res[(s, "s10")][1] for s in suites])
        c6 = np.concatenate([res[(s, "s6b")][1] for s in suites])
        a10 = np.concatenate([res[(s, "s10")][0] for s in suites])
        a6 = np.concatenate([res[(s, "s6b")][0] for s in suites])
        d = boot(e10.astype(float) - e6, rng)
        dc = boot(c10.astype(float) - c6, rng)
        L.append(f"- {name}: SER {d[0]:+.3f} [{d[1]:+.3f}, {d[2]:+.3f}]; correct {dc[0]:+.3f} [{dc[1]:+.3f}, {dc[2]:+.3f}]; coverage {a10.mean() - a6.mean():+.3f}")
    txt = "\n".join(L)
    (OUT / "S10_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
