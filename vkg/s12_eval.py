"""Score S12 (docs/S12_PROTOCOL.md). Run: python -B -m vkg.s12_eval -> results/runs/s12/S12_tables.md
Systems: 4B plain (L1 baseline), 4B cautious (round 0), S11 (reference), S12 (agreement filter), S12 without filter. Grader 6; non-answers by code."""
import json

import numpy as np

from .grade6 import veto
from .probe_gen import ROOT
from .s8_eval import non_answer
from .tasks import matches

R = ROOT / "results" / "runs"
OUT = R / "s12"
J = {(r["question"], r["gold"], r["answer"]): r["grade"] for r in map(json.loads, open(ROOT / "results" / "grader5" / "judge_grades.jsonl", encoding="utf-8"))}


def g6(q, gold, a):
    a = str(a)
    if non_answer(a):
        return None
    g = J[(q, gold[0], a)]
    return g == "CORRECT" and not veto(q, gold[0], a)


def boot(d, rng):
    d = np.asarray(d, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(2000)])
    return d.mean(), bs[50], bs[1949]


def main():
    rng = np.random.default_rng(0)
    rows = [json.loads(l) for l in open(OUT / "outputs.jsonl", encoding="utf-8")]
    f4 = {o["id"]: o["plain"] for o in map(json.loads, open(R / "s8" / "fresh_4b.jsonl", encoding="utf-8"))}
    d4 = {o["id"]: o["plain"] for o in map(json.loads, open(R / "s6b" / "eval_outputs.jsonl", encoding="utf-8")) if o["suite"] == "simpleqa_E"}
    s11 = {o["id"]: o["final"] for o in map(json.loads, open(R / "s11" / "outputs.jsonl", encoding="utf-8"))}
    for r in rows:
        r["plain"] = f4[r["id"]] if r["set"] == "fresh" else d4[r["id"]]
        r["s11"] = s11[r["id"]]
    L = ["# S12: search-on-abstain v2, Qwen3-4B (generated by vkg/s12_eval.py)", "", "Grader 6. SER = answered and wrong / all; correct = correct / all.", ""]
    stats = {}
    for name, sets in (("FRESH", ("fresh",)), ("DEV SimpleQA-E", ("dev",)), ("pooled", ("fresh", "dev"))):
        sub = [r for r in rows if r["set"] in sets]
        L += [f"## {name} (n={len(sub)})", "", "| system | coverage | correct | SER | selective risk |", "|---|---|---|---|---|"]
        for s in ("plain", "round0", "s11", "final_nofilter", "final"):
            g = [g6(r["question"], r["gold"], r[s]) for r in sub]
            a = np.array([x is not None for x in g])
            c = np.array([bool(x) for x in g])
            stats[(name, s)] = (a, c)
            L.append(f"| {dict(plain='plain', round0='cautious', s11='S11', final_nofilter='S12 no filter', final='S12')[s]} | {a.mean():.3f} | {c.mean():.3f} | {(a & ~c).mean():.3f} | {(a & ~c).sum() / max(1, a.sum()):.3f} |")
        a0, c0 = stats[(name, "round0")]
        a1, c1 = stats[(name, "final")]
        d = boot((a1 & ~c1).astype(float) - (a0 & ~c0), rng)
        dc = boot(c1.astype(float) - c0, rng)
        L += ["", f"S12 minus cautious: SER {d[0]:+.3f} [{d[1]:+.3f}, {d[2]:+.3f}]; correct {dc[0]:+.3f} [{dc[1]:+.3f}, {dc[2]:+.3f}]; coverage {a1.mean() - a0.mean():+.3f}"]
        tried = [r for r in sub if r["rounds"]]
        rec = [r for r in tried if any(matches(r["gold"], x["passage"]) for x in r["rounds"] if x["passage"])]
        newc = [r for r in tried if g6(r["question"], r["gold"], r["final"])]
        neww = [r for r in tried if g6(r["question"], r["gold"], r["final"]) is False]
        recc = [r for r in rec if g6(r["question"], r["gold"], r["final"])]
        L += [f"Abstentions searched again: {len(tried)}; gold string found in a new passage (recoverable): {len(rec)}; "
              f"recovered correct among recoverable: {len(recc)}/{len(rec)} = {len(recc) / max(1, len(rec)):.2f}; "
              f"new answers: {len(newc) + len(neww)} ({len(newc)} correct, {len(neww)} wrong, precision {len(newc) / max(1, len(newc) + len(neww)):.2f})",
              f"Cost per searched item: mean {np.mean([len(r['rounds']) for r in tried]) if tried else 0:.2f} rounds, "
              f"{np.mean([r['pages_fetched'] for r in tried]) if tried else 0:.1f} pages, {np.mean([r['gen_tokens'] for r in tried]) if tried else 0:.0f} generated tokens, "
              f"{np.mean([r['prompt_tokens'] for r in tried]) if tried else 0:.0f} prompt tokens, {np.mean([r['sec'] for r in tried]) if tried else 0:.1f} s", ""]
        if name == "pooled":
            L.append("New wrong answers (pooled):")
            L += [f"- {r['id']}: Q: {r['question'][:90]} | gold {r['gold'][0][:50]} | S12 {str(r['final'])[:60]}" for r in neww]
            L.append("")
    txt = "\n".join(L)
    (OUT / "S12_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
