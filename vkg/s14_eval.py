"""Score S14 (docs/S14_PROTOCOL.md). Run: python -B -m vkg.s14_eval -> results/runs/s14/S14_tables.md
Systems (all Qwen3-4B, greedy; non-answers by code; grader 6.1):
  plain        4B plain on the Wikipedia passage (pre-registered L1 baseline)
  cautious     4B cautious on the Wikipedia passage (round 0)
  S13          reference (web search on abstain only)
  web_plain    4B plain on the web passage, every item (equal-budget baseline)
  web_cautious 4B cautious on the web passage, every item
  S14 strict   round0 answered -> kept only if web_cautious or web_plain agrees with it, else abstain;
               round0 abstained -> web_cautious if web_plain agrees (S13 rule), else abstain
  S14 lenient  round0 answered -> kept unless web_cautious gives a different (non-abstaining) answer; abstained -> S13 rule
  S14 strict + format guard: also abstain when the question asks a full date (or month and year) and the answer lacks those parts
               (question and answer only; no gold)."""
import json

import numpy as np

from .grade6 import _asks_full_date, _asks_month_year, veto
from .probe_gen import ROOT
from .s12_run import agree
from .s8_eval import non_answer
from .support_check import date_parts, tokens

R = ROOT / "results" / "runs"
OUT = R / "s14"
J = {(r["question"], r["gold"], r["answer"]): r["grade"] for r in map(json.loads, open(ROOT / "results" / "grader5" / "judge_grades.jsonl", encoding="utf-8"))}
ABST = "I don't know"


def g6(q, gold, a):
    if a is None or non_answer(str(a)):
        return None
    a = str(a)
    return J[(q, gold[0], a)] == "CORRECT" and not veto(q, gold[0], a)


def ans(x):
    return x is not None and not non_answer(str(x))


def late(r):
    return r["web_cautious"] if ans(r["web_cautious"]) and agree(r["web_cautious"], r["web_plain"] or "") else ABST


def strict(r):
    if ans(r["round0"]):
        ok = (ans(r["web_cautious"]) and agree(r["round0"], r["web_cautious"])) or (ans(r["web_plain"]) and agree(r["round0"], r["web_plain"]))
        return r["round0"] if ok else ABST
    return late(r)


def lenient(r):
    if ans(r["round0"]):
        conflict = ans(r["web_cautious"]) and not agree(r["round0"], r["web_cautious"])
        return ABST if conflict else r["round0"]
    return late(r)


def fmt_ok(q, a):
    ap = date_parts(tokens(str(a)))
    if _asks_full_date(q) and not (ap and ap[0] and ap[2]):
        return False
    if _asks_month_year(q) and not (ap and ap[2]):
        return False
    return True


def strict_fmt(r):
    a = strict(r)
    return a if (not ans(a) or fmt_ok(r["question"], a)) else ABST


def boot(d, rng):
    d = np.asarray(d, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(2000)])
    return d.mean(), bs[50], bs[1949]


SYS = (("plain", "plain"), ("cautious", "round0"), ("S13", "s13"), ("web_plain", "web_plain"), ("web_cautious", "web_cautious"),
       ("S14 strict", "s14"), ("S14 lenient", "s14l"), ("S14 strict + format guard", "s14f"))


def main():
    rng = np.random.default_rng(0)
    rows = [json.loads(l) for l in open(OUT / "outputs.jsonl", encoding="utf-8")]
    f4 = {o["id"]: o["plain"] for o in map(json.loads, open(R / "s8" / "fresh_4b.jsonl", encoding="utf-8"))}
    d4 = {o["id"]: o["plain"] for o in map(json.loads, open(R / "s6b" / "eval_outputs.jsonl", encoding="utf-8")) if o["suite"] == "simpleqa_E"}
    s13 = {o["id"]: o for o in map(json.loads, open(R / "s13" / "outputs.jsonl", encoding="utf-8"))}
    same = 0
    for r in rows:
        r["plain"] = f4[r["id"]] if r["set"] == "fresh" else d4[r["id"]]
        r["s13"] = s13[r["id"]]["final"]
        r["s14"], r["s14l"], r["s14f"] = strict(r), lenient(r), strict_fmt(r)
        if not ans(r["round0"]) and str(late(r)) == str(r["s13"]) or ans(r["round0"]):
            same += 1
    L = ["# S14: web corroboration for every item, Qwen3-4B (generated by vkg/s14_eval.py)", "",
         "Grader 6.1. SER = answered and wrong / all; correct = correct / all; selective risk = wrong / answered.",
         f"Consistency check: S14's late answer equals S13's on {same}/{len(rows)} items (round-0 answered items count as equal).", ""]
    for name, sets in (("FRESH", ("fresh",)), ("DEV SimpleQA-E", ("dev",)), ("pooled", ("fresh", "dev"))):
        sub = [r for r in rows if r["set"] in sets]
        L += [f"## {name} (n={len(sub)})", "", "| system | coverage | correct | SER | selective risk |", "|---|---|---|---|---|"]
        M = {}
        for label, key in SYS:
            g = [g6(r["question"], r["gold"], r[key]) for r in sub]
            a = np.array([x is not None for x in g])
            c = np.array([bool(x) for x in g])
            M[label] = (a, c)
            L.append(f"| {label} | {a.mean():.3f} | {c.mean():.3f} | {(a & ~c).mean():.3f} | {(a & ~c).sum() / max(1, a.sum()):.3f} |")
        L.append("")
        for x, y in (("S14 strict", "plain"), ("S14 strict", "web_plain"), ("S14 strict + format guard", "plain"), ("S14 strict + format guard", "web_plain"),
                     ("S14 lenient", "web_plain"), ("S14 strict", "S13")):
            (ax, cx), (ay, cy) = M[x], M[y]
            ser = boot((ax & ~cx).astype(int) - (ay & ~cy).astype(int), rng)
            cor = boot(cx.astype(int) - cy.astype(int), rng)
            L.append(f"{x} minus {y}: SER {ser[0]:+.3f} [{ser[1]:+.3f}, {ser[2]:+.3f}]; correct {cor[0]:+.3f} [{cor[1]:+.3f}, {cor[2]:+.3f}]; "
                     f"coverage {ax.mean() - ay.mean():+.3f}")
        if name == "pooled":
            tr = [r for r in rows]
            L += ["", f"Cost per item: {np.mean([len(r['urls']) for r in tr]):.1f} pages, {np.mean([r['gen_tokens'] for r in tr]):.0f} generated tokens, "
                  f"{np.mean([r['prompt_tokens'] for r in tr]):.0f} prompt tokens, {np.mean([r['sec'] for r in tr]):.1f} s; "
                  f"contaminated pages dropped {sum(len(r['dropped_contaminated']) for r in tr)} of {sum(len(r['kept']) + len(r['dropped_contaminated']) for r in tr)} with text"]
        L.append("")
    txt = "\n".join(L)
    (OUT / "S14_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
