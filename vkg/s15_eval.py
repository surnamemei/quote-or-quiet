"""Score the FRESH-2 confirmation (docs/S15_PROTOCOL.md). Run: python -B -m vkg.s15_eval -> results/runs/s15/S15_tables.md
Primary system: S14 strict (rule in vkg/s14_eval.py, unchanged). Baselines: 4B plain on the Wikipedia passage (L1-A) and
4B plain on the web passage (L1-B, equal budget). Grader 6.1; non-answers by code. One-sided 95% bounds by paired bootstrap
(10000 draws, seed 0); Clopper-Pearson upper bound for SER (L2 reference)."""
import json

import numpy as np
from scipy.stats import beta

from .probe_gen import ROOT
from .s14_eval import g6, lenient, strict, strict_fmt

OUT = ROOT / "results" / "runs" / "s15"
SYS = (("plain (Wikipedia)", "plain"), ("cautious (Wikipedia)", "round0"), ("web_plain", "web_plain"), ("web_cautious", "web_cautious"),
       ("S14 strict", "s14"), ("S14 lenient", "s14l"), ("S14 strict + format guard", "s14f"))


def lo_hi(d, rng):
    d = np.asarray(d, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(10000)])
    return d.mean(), bs[500], bs[9499]          # one-sided 95% lower / upper


def cp_upper(k, n):
    return 1.0 if k >= n else float(beta.ppf(0.95, k + 1, n - k))


def main():
    rng = np.random.default_rng(0)
    rows = [json.loads(l) for l in open(OUT / "outputs.jsonl", encoding="utf-8")]
    for r in rows:
        r["s14"], r["s14l"], r["s14f"] = strict(r), lenient(r), strict_fmt(r)
    n = len(rows)
    M = {}
    L = ["# S15: FRESH-2 confirmation, Qwen3-4B (generated by vkg/s15_eval.py)", "", f"n = {n}. Grader 6.1.", "",
         "| system | coverage | correct | SER | selective risk | SER 95% upper (CP) |", "|---|---|---|---|---|---|"]
    for label, key in SYS:
        g = [g6(r["question"], r["gold"], r[key]) for r in rows]
        a = np.array([x is not None for x in g])
        c = np.array([bool(x) for x in g])
        e = a & ~c
        M[label] = (a, c, e)
        L.append(f"| {label} | {a.mean():.3f} | {c.mean():.3f} | {e.mean():.3f} | {e.sum() / max(1, a.sum()):.3f} | {cp_upper(int(e.sum()), n):.3f} |")
    L.append("")
    verdict = {}
    for sysname in ("S14 strict", "S14 strict + format guard"):
        for crit, base in (("L1-A", "plain (Wikipedia)"), ("L1-B", "web_plain")):
            a, c, e = M[sysname]
            ab, cb, eb = M[base]
            s = lo_hi(e.astype(float) - 0.5 * eb.astype(float), rng)
            y = lo_hi(c.astype(int) - cb.astype(int), rng)
            cov = a.mean() - ab.mean()
            ok_a = s[2] < 0
            ok_b = y[0] >= 0 and y[1] > -0.03
            ok_c = cov >= -0.03
            verdict[(sysname, crit)] = ok_a and ok_b and ok_c
            L += [f"### {sysname} vs {base} ({crit})",
                  f"- (a) SER at most half the baseline's: mean(e - 0.5 e_base) = {s[0]:+.4f}, one-sided 95% upper {s[2]:+.4f} -> {'pass' if ok_a else 'fail'}",
                  f"- (b) yield not lower: correct diff {y[0]:+.3f}, one-sided 95% lower {y[1]:+.3f} (needs point >= 0 and lower > -0.03) -> {'pass' if ok_b else 'fail'}",
                  f"- (c) coverage not lower by more than 3 points: {cov:+.3f} -> {'pass' if ok_c else 'fail'}",
                  f"- **{crit}: {'MET' if verdict[(sysname, crit)] else 'NOT MET'}**", ""]
    tr = rows
    L += [f"Cost per item: {np.mean([len(r['urls']) for r in tr]):.1f} pages, {np.mean([r['gen_tokens'] for r in tr]):.0f} generated tokens, "
          f"{np.mean([r['prompt_tokens'] for r in tr]):.0f} prompt tokens, {np.mean([r['sec'] for r in tr]):.1f} s (web stage); "
          f"contaminated pages dropped {sum(len(r['dropped_contaminated']) for r in tr)} of {sum(len(r['kept']) + len(r['dropped_contaminated']) for r in tr)} with text"]
    txt = "\n".join(L)
    (OUT / "S15_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
