"""Score S17 (docs/S17_PROTOCOL.md). Run: python -B -m vkg.s17_eval <set>   (set: fresh | fresh3) -> results/runs/s17/S17_<set>_tables.md
Support score: for the candidate answers of the three evidence sources (web, wiki, combo; each source = its plain and cautious answers),
support(a) = number of sources with at least one answer that agrees with a (vkg.s12_run.agree). The max-support candidate is chosen
(ties: first in the order web_plain, web_cautious, wiki_plain, wiki_cautious, combo_plain, combo_cautious); s = its support (0-3).
Systems:  MS2 = answer the max-support candidate iff s >= 2;  MS3 = iff s == 3.
Baselines: wiki_plain (4B plain on the Wikipedia passage; L1-A), combo_plain (4B plain on the combined passage; L1-B single pass),
           MSany (max-support candidate, always answered: same evidence and generations as MS2; L1-B equal generation).
L1 criteria as S15 (one-sided 95% paired bootstrap, 10000 draws, seed 0): (a) upper bound of mean(e - 0.5 e_base) < 0;
(b) correct diff >= 0 (point) and lower bound > -0.03; (c) coverage diff >= -0.03.
L2: Clopper-Pearson one-sided 95% upper bound on SER (errors / all items) < 0.01.
L3: conformal risk control (vkg/crc.py) on the support score, calibrated on DEV (results/runs/s16, same pipeline) + FRESH,
    alpha in {0.01, 0.05}; test-set SER at the calibrated threshold is reported against alpha."""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import beta

from . import crc
from .s12_run import agree
from .s14_eval import ABST, ans, g6

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "runs" / "s17"
ORDER = ("web_plain", "web_cautious", "wiki_plain", "wiki_cautious", "combo_plain", "combo_cautious")
SRCS = (("web_plain", "web_cautious"), ("wiki_plain", "wiki_cautious"), ("combo_plain", "combo_cautious"))


def support(r, a):
    return sum(any(ans(r[k]) and agree(a, r[k]) for k in s) for s in SRCS)


def cand(r):
    c = [r[k] for k in ORDER if ans(r[k])]
    if not c:
        return ABST, 0
    best = max(c, key=lambda x: support(r, x))              # max() keeps the first of equal keys
    return best, support(r, best)


SYSTEMS = {"MS2": lambda r: (lambda a, s: a if s >= 2 else ABST)(*cand(r)),
           "MS3": lambda r: (lambda a, s: a if s >= 3 else ABST)(*cand(r)),
           "wiki_plain": lambda r: r["wiki_plain"], "combo_plain": lambda r: r["combo_plain"],
           "MSany": lambda r: cand(r)[0]}


def outcomes(rows, f):
    g = [g6(r["question"], r["gold"], f(r)) for r in rows]
    a = np.array([x is not None for x in g])
    c = np.array([bool(x) for x in g])
    return a, c, a & ~c


def lo_hi(d, rng):
    d = np.asarray(d, float)
    bs = np.sort(d[rng.integers(0, len(d), (10000, len(d)))].mean(1))
    return d.mean(), bs[500], bs[9499]


def cp_upper(k, n):
    return 1.0 if k >= n else float(beta.ppf(0.95, k + 1, n - k))


def dev_rows():
    L = lambda t: {r["id"]: r for r in map(json.loads, open(ROOT / f"results/runs/s16/{t}_outputs.jsonl", encoding="utf-8"))}
    W, K, C = L("k8"), L("wiki"), L("combo")
    out = []
    for i, r in W.items():
        out.append({"id": i, "question": r["question"], "gold": r["gold"], "web_plain": r["web_plain"], "web_cautious": r["web_cautious"],
                    "wiki_plain": K[i]["web_plain"], "wiki_cautious": K[i]["web_cautious"],
                    "combo_plain": C[i]["web_plain"], "combo_cautious": C[i]["web_cautious"]})
    return out


def table(rows, title):
    n = len(rows)
    L = [f"### {title} (n = {n})", "", "| system | coverage | correct | SER | SER 95% upper (CP) |", "|---|---|---|---|---|"]
    M = {}
    for k, f in SYSTEMS.items():
        a, c, e = outcomes(rows, f)
        M[k] = (a, c, e)
        L.append(f"| {k} | {a.mean():.3f} | {c.mean():.3f} | {e.mean():.3f} | {cp_upper(int(e.sum()), n):.4f} |")
    return L, M


def main():
    name = sys.argv[1]
    rng = np.random.default_rng(0)
    rows = [json.loads(l) for l in open(OUT / f"{name}_outputs.jsonl", encoding="utf-8")]
    L = [f"# S17 on {name} (generated by vkg/s17_eval.py)", "", "Grader 6.1. Cells are rates over all items.", ""]
    T, M = table(rows, "pooled")
    L += T + [""]
    if name == "fresh3":
        for st in ("V", "O"):
            L += table([r for r in rows if r.get("stratum") == st], f"stratum {st}")[0] + [""]
    for sysn, crit, base in (("MS2", "L1-A", "wiki_plain"), ("MS2", "L1-B single", "combo_plain"), ("MS2", "L1-B equal-gen", "MSany")):
        a, c, e = M[sysn]
        ab, cb, eb = M[base]
        s = lo_hi(e.astype(float) - 0.5 * eb.astype(float), rng)
        y = lo_hi(c.astype(int) - cb.astype(int), rng)
        cov = a.mean() - ab.mean()
        ok = (s[2] < 0, y[0] >= 0 and y[1] > -0.03, cov >= -0.03)
        L += [f"#### {sysn} vs {base} ({crit})",
              f"- (a) mean(e - 0.5 e_base) = {s[0]:+.4f}, one-sided 95% upper {s[2]:+.4f} -> {'pass' if ok[0] else 'fail'}",
              f"- (b) correct diff {y[0]:+.3f}, one-sided 95% lower {y[1]:+.3f} -> {'pass' if ok[1] else 'fail'}",
              f"- (c) coverage diff {cov:+.3f} -> {'pass' if ok[2] else 'fail'}",
              f"- **{crit}: {'MET' if all(ok) else 'NOT MET'}**", ""]
    k3 = int(M["MS3"][2].sum())
    L += [f"#### L2 (MS3): {k3} silent errors in {len(rows)}; CP 95% upper {cp_upper(k3, len(rows)):.4f} -> "
          f"**{'MET' if cp_upper(k3, len(rows)) < 0.01 else 'NOT MET'}** (coverage {M['MS3'][0].mean():.3f})", ""]
    cal = dev_rows() + ([json.loads(l) for l in open(OUT / "fresh_outputs.jsonl", encoding="utf-8")] if name == "fresh3" else [])
    cs = [cand(r)[1] for r in cal]
    ce = [bool(e) for e in outcomes(cal, lambda r: cand(r)[0])[2]]
    ts = np.array([cand(r)[1] for r in rows])
    te = outcomes(rows, lambda r: cand(r)[0])[2]
    L += [f"#### L3: conformal risk control on the support score (calibration n = {len(cal)}: DEV" + (" + FRESH" if name == "fresh3" else "") + ")"]
    for alpha in (0.01, 0.05):
        lam, rcal, covcal = crc.calibrate(cs, ce, alpha)
        m = crc.apply(ts, lam)
        L.append(f"- alpha {alpha}: threshold s >= {lam:g} (calibration SER {rcal:.4f}, coverage {covcal:.3f}); "
                 f"test SER {float((te & m).mean()):.4f}, coverage {float(m.mean()):.3f}")
    L += ["", f"Cost per item: {np.mean([r['prompt_tokens'] for r in rows]):.0f} prompt tokens, {np.mean([r['gen_tokens'] for r in rows]):.0f} generated tokens, "
          f"{np.mean([len(r['web_urls']) for r in rows]):.1f} web pages; contaminated pages dropped {sum(len(r['web_dropped']) for r in rows)}"]
    txt = "\n".join(L)
    (OUT / f"S17_{name}_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
