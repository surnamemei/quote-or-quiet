"""S18 scorer: the sealed L2 test with the L3 gate (docs/S18_PROTOCOL.md).
Systems (all on the S17 pipeline outputs, results/runs/s17/<set>_outputs.jsonl):
  G3 (primary, L2)   : L3 gate (vkg/l3_verify.release) on the max-support candidate, released only if support s = 3
  G2 (secondary)     : the same with s >= 2
  baselines (L1, reported): wiki_plain, combo_plain, MSany (vkg/s17_eval.py)
Steps:
  python -B -m vkg.s18_eval raw <sets...>    raw scores (grader 6.1) + writes results/runs/s18/audit_sheet.csv
  (auditor fills the 'verdict' column of the sheet; see the protocol)
  python -B -m vkg.s18_eval audited <sets...>   final L2 verdict from the filled sheet
L2 (pre-registered, PRIMARY = gold-relative): for G3, (i) coverage >= 0.35 (pre-specified completion floor) and (ii) a
one-sided 95% upper bound on SER < 0.01, where errors are judged against the benchmark gold by grader 6.1 and corrected for
the grader's false credit (truly wrong answers it grades correct). By Bonferroni (2.5% + 2.5%):
  f_up = Clopper-Pearson 97.5% upper bound on grader-6 false credit from its blind validation: 1 credited of 677 truly wrong
         answers (V1+V2+V3 natural rows: 1/351; P0.2 injection, effective: 0/326; docs/GRADER6_PROTOCOL.md);
  k_raw = G3 releases graded wrong;  E = ceil(k_raw / (1 - f_up)) bounds the true errors (hidden = false credit x true errors);
  SER upper = Clopper-Pearson 97.5% upper bound with E errors in n items.
Assumption: grader-6 false credit on S18 answers is no higher than on its validation rows (stated in the protocol).
SENSITIVITY (not the verdict): a human gold audit of the graded-wrong releases only (one-directional: it can only remove
errors), reported as "gold-adjusted" next to the primary."""
import csv
import json
import math
import random
import sys
from pathlib import Path

import numpy as np
from scipy.stats import beta

from . import l3_verify as V
from . import localwiki as LW
from . import s17_eval as S
from .s14_eval import ans, g6

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "runs" / "s18"
FLOOR = 0.35
FALSE_CREDIT = (1, 677)      # (credited, truly wrong) from the grader-6 blind validation + effective injection result
SHEET = OUT / "audit_sheet.csv"


def cp(k, n, conf=0.95):
    return 1.0 if k >= n else float(beta.ppf(conf, k + 1, n - k))


def gated(rows):
    out = []
    for r in rows:
        a, s = S.cand(r)
        rel, rec = V.release(r["question"], a if ans(a) else None, r["wiki_titles"], LW.page_text)
        out.append({"id": r["id"], "set": r["set"], "stratum": r.get("stratum"), "question": r["question"], "gold": r["gold"],
                    "support": s, "released": rel, "doc": rec.get("doc"), "span": rec.get("span"), "reason": rec["reason"],
                    "graded": g6(r["question"], r["gold"], rel) if rel else None})
    return out


def load(sets):
    rows = []
    for s in sets:
        rows += [json.loads(l) for l in open(ROOT / "results/runs/s17" / f"{s}_outputs.jsonl", encoding="utf-8")]
    return rows


def raw(sets):
    OUT.mkdir(parents=True, exist_ok=True)
    rows = load(sets)
    G = gated(rows)
    n = len(G)
    L = [f"# S18 raw scores on {'+'.join(sets)} (n = {n}; generated by vkg/s18_eval.py)", "",
         "| system | coverage | correct | SER (raw) | SER 95% upper (CP) |", "|---|---|---|---|---|"]
    for name, k in (("G3: L3 gate, all 3 agree", 3), ("G2: L3 gate, >= 2 agree", 2)):
        rel = [g for g in G if g["released"] and g["support"] >= k]
        w = sum(g["graded"] is False for g in rel)
        c = sum(g["graded"] is True for g in rel)
        L.append(f"| {name} | {len(rel) / n:.3f} | {c / n:.3f} | {w / n:.4f} | {cp(w, n):.4f} |")
    for name, f in (("wiki_plain", S.SYSTEMS["wiki_plain"]), ("combo_plain", S.SYSTEMS["combo_plain"]), ("MSany", S.SYSTEMS["MSany"])):
        a, c, e = S.outcomes(rows, f)
        L.append(f"| {name} | {a.mean():.3f} | {c.mean():.3f} | {e.mean():.4f} | {cp(int(e.sum()), n):.4f} |")
    for st in ("V", "O"):
        sub = [g for g in G if g["stratum"] == st]
        if sub:
            rel = [g for g in sub if g["released"] and g["support"] >= 3]
            L.append(f"\nG3 stratum {st}: n={len(sub)}, coverage {len(rel) / len(sub):.3f}, raw SER {sum(g['graded'] is False for g in rel) / len(sub):.4f}")
    # primary L2 (gold-relative, false-credit corrected)
    f_up = cp(FALSE_CREDIT[0], FALSE_CREDIT[1], 0.975)
    L.append("")
    for name, k in (("G3 (primary)", 3), ("G2 (secondary)", 2)):
        rel = [g for g in G if g["released"] and g["support"] >= k]
        k_raw = sum(g["graded"] is False for g in rel)
        E = math.ceil(k_raw / (1 - f_up))
        up = cp(E, n, 0.975)
        cov = len(rel) / n
        met = cov >= FLOOR and up < 0.01
        L += [f"## L2, {name}: coverage {cov:.3f} (floor {FLOOR}) {'pass' if cov >= FLOOR else 'fail'}; graded-wrong {k_raw}; "
              f"false-credit bound f_up {f_up:.4f} -> true errors <= {E}; SER upper (97.5%, Bonferroni) {up:.4f} -> "
              f"{'pass' if up < 0.01 else 'fail'}; **{'MET' if met else 'NOT MET'}**"]
    # audit sheet (sensitivity only): every graded-wrong G2 release, shuffled, without system internals
    rel2 = [g for g in G if g["released"] and g["support"] >= 2]
    wrong = [g for g in rel2 if g["graded"] is False]
    sample = []
    rng = random.Random(18)
    audit = [dict(g, bucket="graded_wrong") for g in wrong]
    rng.shuffle(audit)
    with open(SHEET, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["row", "id", "question", "gold", "released_answer", "source_document", "source_span", "verdict", "note"])
        for i, g in enumerate(audit):
            w.writerow([i, g["id"], g["question"], g["gold"][0], g["released"], g["doc"], g["span"], "", ""])
    json.dump({"support": {g["id"]: g["support"] for g in rel2}, "n": n,
               "n_released": {k: sum(1 for g in rel2 if g["support"] >= k) for k in (2, 3)}}, open(OUT / "audit_key.json", "w", encoding="utf-8"))
    L += ["", f"Sensitivity audit sheet: {SHEET} ({len(wrong)} graded-wrong G2 releases, shuffled)."]
    txt = "\n".join(L)
    (OUT / f"S18_raw_{'_'.join(sets)}.md").write_text(txt, encoding="utf-8")
    print(txt)


def audited(sets):
    """Sensitivity only: gold-adjusted SER after a human audit of the graded-wrong releases (one-directional)."""
    key = json.load(open(OUT / "audit_key.json", encoding="utf-8"))
    rows = list(csv.DictReader(open(SHEET, encoding="utf-8-sig")))
    allowed = {"correct", "wrong", "gold_wrong", "unresolvable"}
    bad = [r["row"] for r in rows if r["verdict"].strip().lower() not in allowed]
    if bad:
        sys.exit(f"audit sheet incomplete or invalid verdicts in rows {bad[:10]} (allowed: {sorted(allowed)})")
    n = key["n"]
    f_up = cp(FALSE_CREDIT[0], FALSE_CREDIT[1], 0.975)
    L = [f"# S18 gold-adjusted sensitivity on {'+'.join(sets)} (n = {n}); NOT the L2 verdict (one-directional audit)", ""]
    for k in (3, 2):
        sub = [r for r in rows if key["support"][r["id"]] >= k]
        k_adj = sum(1 for r in sub if r["verdict"].strip().lower() in ("wrong", "unresolvable"))
        E = math.ceil(k_adj / (1 - f_up))
        L.append(f"- {'G3' if k == 3 else 'G2'}: graded-wrong {len(sub)}, still wrong after audit {k_adj} "
                 f"(gold wrong or answer acceptable: {len(sub) - k_adj}); gold-adjusted SER upper {cp(E, n, 0.975):.4f}")
    txt = "\n".join(L)
    (OUT / f"S18_goldadjusted_{'_'.join(sets)}.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    {"raw": raw, "audited": audited}[sys.argv[1]](sys.argv[2:])
