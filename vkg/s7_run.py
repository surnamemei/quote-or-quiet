"""S7: does the 4B model's hidden state signal that the passage in front of it does NOT contain the answer (evidence sufficiency)?
Stages (inside venv_gpu): python -B -m vkg.s7_run extract [--random-init] | analyze
Features: hidden states at the last prompt token of the plain passage prompt (before any answer), 11 layers, base model (no LoRA).
Train: the 3000 SQuAD 2.0 items of S6b (label = answerable; dataset-provided). Tests: SQuAD2 held-out (300, label = answerable),
SimpleQA-E (300, label = the gold answer is present in the passage by string matching, strict OR repaired matcher; no model involved),
FaithEval unanswerable (150) reported separately (all insufficient). Controls: question-in-passage token recall, TF-IDF of the question,
probe on a random-initialised copy, shuffled labels; and the model's own abstentions from S6b (cautious prompt, trained LoRA) as binary detectors.
"""
import json
import re
import sys
from pathlib import Path

import numpy as np
import torch
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score

from .grade_open import repaired
from .probe_eval import boot, fit_layers, score_layers, auc, CS
from .probe_gen import LAYERS, ROOT
from .retrieval import _tok
from .s6b_run import MODEL, PLAIN, is_unknown
from .tasks import matches

OUT = ROOT / "results" / "runs" / "s7"
S6B = ROOT / "results" / "runs" / "s6b"


def load_sets():
    train = json.load(open(S6B / "train.json", encoding="utf-8"))
    ev = json.load(open(S6B / "eval_items.json", encoding="utf-8"))
    sq = [e for e in ev if e["suite"] == "squad2"]
    fa = [e for e in ev if e["suite"] == "faitheval" and e["kind"] == "unanswerable"]
    sa = [e for e in ev if e["suite"] == "simpleqa_E"]
    return train, sq, fa, sa


def coverage(e):
    return bool(matches(e["gold"], e["passage"]) or repaired(e["gold"][0], e["passage"], hedge_check=False))


def stage_extract(random_init):
    from transformers import AutoConfig, AutoModelForCausalLM, AutoTokenizer
    OUT.mkdir(parents=True, exist_ok=True)
    train, sq, fa, sa = load_sets()
    items = [{"passage": t["passage"], "question": t["question"]} for t in train] + [{"passage": e["passage"], "question": e["question"]} for e in sq + fa + sa]
    tok = AutoTokenizer.from_pretrained(MODEL)
    tok.padding_side = "left"
    if random_init:
        torch.manual_seed(0)
        m = AutoModelForCausalLM.from_config(AutoConfig.from_pretrained(MODEL), dtype=torch.bfloat16).cuda().eval()
    else:
        m = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.bfloat16).cuda().eval()
    prompts = [tok.apply_chat_template([{"role": "user", "content": PLAIN.format(p=e["passage"], q=e["question"])}], add_generation_prompt=True, tokenize=False) for e in items]
    order = sorted(range(len(prompts)), key=lambda i: len(prompts[i]))
    feats = np.zeros((len(items), len(LAYERS), m.config.hidden_size), dtype=np.float16)
    bs = 4
    for s in range(0, len(order), bs):
        idx = order[s:s + bs]
        enc = tok([prompts[i] for i in idx], return_tensors="pt", padding=True).to("cuda")
        with torch.no_grad():
            hs = m(**enc, output_hidden_states=True, logits_to_keep=1).hidden_states
        for j, l in enumerate(LAYERS):
            feats[idx, j] = hs[l][:, -1, :].float().cpu().numpy().astype(np.float16)
        if (s // bs) % 100 == 0:
            print(f"  {s + len(idx)}/{len(order)}", flush=True)
    np.save(OUT / ("feats_random.npy" if random_init else "feats_trained.npy"), feats)
    print("done", feats.shape)


def recall_score(e):
    q = set(_tok(e["question"]))
    p = set(_tok(e["passage"]))
    return len(q & p) / max(1, len(q))


def analyze():
    train, sq, fa, sa = load_sets()
    Ft = np.load(OUT / "feats_trained.npy")
    Fr = np.load(OUT / "feats_random.npy") if (OUT / "feats_random.npy").exists() else None
    n_tr, n_sq, n_fa, n_sa = len(train), len(sq), len(fa), len(sa)
    ytr = np.array([t["target"] != "unknown" for t in train], dtype=int)
    tr = np.arange(n_tr)
    i_sq = np.arange(n_tr, n_tr + n_sq)
    i_fa = np.arange(n_tr + n_sq, n_tr + n_sq + n_fa)
    i_sa = np.arange(n_tr + n_sq + n_fa, n_tr + n_sq + n_fa + n_sa)
    y_sq = np.array([e["kind"] == "answerable" for e in sq], dtype=int)
    y_sa = np.array([coverage(e) for e in sa], dtype=int)
    yall = np.concatenate([ytr, y_sq, np.zeros(n_fa, int), y_sa])
    j, C, ss, m, tab = fit_layers(Ft, yall, tr)
    L = ["# S7: does the 4B model's hidden state signal whether the passage contains the answer? (generated by vkg/s7_run.py analyze)", "",
         f"Train: {n_tr} SQuAD2 items ({ytr.sum()} answerable). Tests: SQuAD2 held-out {n_sq} ({y_sq.sum()} answerable), SimpleQA-E {n_sa} ({y_sa.sum()} passages contain the gold answer; {n_sa - y_sa.sum()} do not), FaithEval unanswerable {n_fa} (all insufficient).",
         f"Probe layer by inner CV: hidden_states[{LAYERS[j]}], C={C}; per-layer CV AUROC: " + ", ".join(f"{LAYERS[t[0]]}:{t[1]:.3f}" for t in tab), ""]
    scores = {"probe": score_layers(Ft, j, ss, m, np.arange(len(yall)))}
    if Fr is not None:
        jr, Cr, ssr, mr, tabr = fit_layers(Fr, yall, tr)
        scores["random_init_probe"] = score_layers(Fr, jr, ssr, mr, np.arange(len(yall)))
    allitems = [{"passage": t["passage"], "question": t["question"]} for t in train] + sq + fa + sa
    scores["question_token_recall_in_passage"] = np.array([recall_score(e) for e in allitems])
    tf = TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True).fit([e["question"] for e in allitems[:n_tr]])
    mt = LogisticRegression(C=1.0, class_weight="balanced", max_iter=2000).fit(tf.transform([e["question"] for e in allitems[:n_tr]]), ytr)
    scores["question_only_tfidf"] = mt.decision_function(tf.transform([e["question"] for e in allitems]))
    rng = np.random.default_rng(1)
    ysh = yall.copy()
    ysh[tr] = rng.permutation(yall[tr])
    js, Cs, sss, ms, _ = fit_layers(Ft, ysh, tr)
    scores["shuffled_labels_probe"] = score_layers(Ft, js, sss, ms, np.arange(len(yall)))
    # the model's own abstentions (S6b eval outputs; same items)
    outs = [json.loads(l) for l in open(S6B / "eval_outputs.jsonl", encoding="utf-8")]
    def own(sysname, suite, kinds=None):
        sel = [o for o in outs if o["suite"] == suite]
        return np.array([0.0 if is_unknown(o[sysname]) else 1.0 for o in sel])
    own_sq = {"own_cautious_answers": own("cautious", "squad2"), "own_trained_answers": own("trained", "squad2")}
    own_sa = {"own_cautious_answers": own("cautious", "simpleqa_E"), "own_trained_answers": own("trained", "simpleqa_E")}
    for name, idx, y, own_d in (("SQuAD2 held-out (in distribution)", i_sq, y_sq, own_sq), ("SimpleQA-E (retrieved Wikipedia passages; label = passage contains the gold answer)", i_sa, y_sa, own_sa)):
        names = list(scores) + list(own_d)
        sl = [scores[n][idx] for n in scores] + [own_d[n] for n in own_d]
        res, diffs = boot(y, sl)
        L += [f"## {name}: AUROC for 'passage is sufficient' [95% bootstrap CI]; sufficient {int(y.sum())} of {len(y)}", "", "| score | AUROC | probe minus score (paired) |", "|---|---|---|"]
        for k, n in enumerate(names):
            d = "" if k == 0 else f"{diffs[k-1][0]:+.3f} [{diffs[k-1][1]:+.3f}, {diffs[k-1][2]:+.3f}]"
            L.append(f"| {n} | {res[k][0]:.3f} [{res[k][1]:.3f}, {res[k][2]:.3f}] | {d} |")
        L.append("")
    # FaithEval unanswerable: share the probe scores sufficient (above the SQuAD2-train median threshold chosen at equal error)
    thr = np.median(scores["probe"][tr])
    L += ["## FaithEval unanswerable (all insufficient)", "",
          f"Share of passages the probe calls sufficient at the SQuAD2-train median score: {np.mean(scores['probe'][i_fa] > thr):.3f} (a perfect detector gives 0). "
          f"On SQuAD2 held-out unanswerable the same threshold gives {np.mean(scores['probe'][i_sq][y_sq == 0] > thr):.3f}; on answerable {np.mean(scores['probe'][i_sq][y_sq == 1] > thr):.3f}.", ""]
    txt = "\n".join(L)
    (OUT / "S7_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    if sys.argv[1] == "extract":
        stage_extract("--random-init" in sys.argv)
    else:
        analyze()
