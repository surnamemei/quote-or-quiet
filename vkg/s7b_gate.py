"""S7b: the S7 evidence-sufficiency probe used as an ANSWER GATE. CPU only, no new generation.
Inputs (all frozen before this script): S7 features (results/runs/s7/feats_trained.npy), S6b outputs (results/runs/s6b/eval_outputs.jsonl:
plain, cautious, trained answers of Qwen3-4B on SQuAD2 held-out, FaithEval, SimpleQA-E), and the frozen 27B run on the same 300 SimpleQA-E
questions/passages (results/runs/openworld_simpleqa_hybrid_qwen3.8-27b_s3000_n300.jsonl).
Gate: answer only if probe score > T. T is fixed on SQuAD2 TRAIN only = median of the probe's training scores (T50). No test data used to set T.
Coverage-matched variant: keep the top-k probe scores where k = number of items the cautious system answers (compares the signal, not the threshold).
Run: venv_gpu/Scripts/python -B -m vkg.s7b_gate
"""
import json

import numpy as np

from .analyze_open import att, cor_rep
from .probe_gen import ROOT
from .s6a_clean import is_unknown2
from .s6b_run import is_unknown, outcome
from .s7_run import OUT as S7OUT, S6B, coverage, load_sets
from .probe_eval import fit_layers, score_layers, correct
from .tasks import matches

OUT = ROOT / "results" / "runs" / "s7b"
BIG = ROOT / "results" / "runs" / "openworld_simpleqa_hybrid_qwen3.8-27b_s3000_n300.jsonl"


def outcome_d(r, ans):
    """Same as s6b outcome but with the denial-aware abstention detector (sensitivity)."""
    answered = not is_unknown2(ans)
    if r["suite"] == "squad2" and r["kind"] == "answerable":
        ok = answered and matches(r["gold"], ans)
    elif r["suite"] == "simpleqa_E":
        ok = answered and bool(correct({"dataset": "simpleqa", "gold": r["gold"]}, ans))
    else:
        ok = False
    return answered, ok, answered and not ok


def boot_diff(a, b, rng, n=2000):
    d = np.asarray(a, float) - np.asarray(b, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(n)])
    return d.mean(), bs[int(0.025 * n)], bs[int(0.975 * n) - 1]


def main():
    train, sq, fa, sa = load_sets()
    F = np.load(S7OUT / "feats_trained.npy")
    n_tr, n_sq, n_fa, n_sa = len(train), len(sq), len(fa), len(sa)
    ytr = np.array([t["target"] != "unknown" for t in train], dtype=int)
    tr = np.arange(n_tr)
    yall = np.concatenate([ytr, np.zeros(n_sq + n_fa + n_sa, int)])        # test labels are not used by fit_layers (train idx only)
    j, C, ss, m, _ = fit_layers(F, yall, tr)
    s = score_layers(F, j, ss, m, np.arange(len(F)))
    T = float(np.median(s[tr]))
    seg = {"squad2": s[n_tr:n_tr + n_sq], "faitheval_unanswerable": s[n_tr + n_sq:n_tr + n_sq + n_fa], "simpleqa_E": s[n_tr + n_sq + n_fa:]}
    outs = [json.loads(l) for l in open(S6B / "eval_outputs.jsonl", encoding="utf-8")]
    rows = {"squad2": [o for o in outs if o["suite"] == "squad2"],
            "faitheval_unanswerable": [o for o in outs if o["suite"] == "faitheval" and o["kind"] == "unanswerable"],
            "simpleqa_E": [o for o in outs if o["suite"] == "simpleqa_E"]}
    # alignment check: S6b output order == S7 item order
    for name, items in (("squad2", sq), ("faitheval_unanswerable", fa), ("simpleqa_E", sa)):
        assert [o["id"] for o in rows[name]] == [e["id"] for e in items], name
    rng = np.random.default_rng(0)
    L = ["# S7b: evidence-sufficiency probe as an answer gate (generated by vkg/s7b_gate.py)", "",
         f"Probe: hidden_states layer index {j}, C={C}, trained on {n_tr} SQuAD2 items only. Threshold T50 = median SQuAD2-train score = {T:.3f} (fixed before looking at any test item).",
         "SER = silent errors / all items; yield = correct / answerable items (SQuAD2: 150 answerable; SimpleQA-E: all 300 count as answerable questions); coverage = answered / all.",
         "gate+X = system X's answer is kept only if probe score > T50; X@matched = plain answers kept for the top-k probe scores, k = items the cautious system answers.", ""]
    summary = {}
    for detector, oc in (("strict abstention detector (project UNKNOWN_RE, as in S6b)", outcome), ("denial-aware abstention detector (sensitivity)", outcome_d)):
        L += [f"# Detector: {detector}", ""]
        for name in ("simpleqa_E", "squad2", "faitheval_unanswerable"):
            R, sc = rows[name], seg[name]
            n = len(R)
            ansable = [i for i, r in enumerate(R) if r["kind"] == "answerable"] if name == "squad2" else list(range(n)) if name == "simpleqa_E" else []
            base = {k: [oc(r, r[k]) for r in R] for k in ("plain", "cautious", "trained")}
            sysv = {}
            for k, o in base.items():
                sysv[k] = o
            g = sc > T
            for k in ("plain", "cautious", "trained"):
                sysv[f"gate+{k}"] = [(a and gi, c and gi, e and gi) for (a, c, e), gi in zip(base[k], g)]
            kcov = sum(a for a, _, _ in base["cautious"])
            top = np.zeros(n, bool)
            top[np.argsort(-sc)[:kcov]] = True
            sysv["plain@matched"] = [(a and gi, c and gi, e and gi) for (a, c, e), gi in zip(base["plain"], top)]
            L += [f"## {name} (n={n}); probe passes {g.mean():.3f} of items at T50", "", "| system | coverage | yield | SER | precision |", "|---|---|---|---|---|"]
            for k, o in sysv.items():
                cov = np.mean([a for a, _, _ in o])
                y = np.mean([o[i][1] for i in ansable]) if ansable else float("nan")
                ser = np.mean([e for _, _, e in o])
                prec = sum(c for _, c, _ in o) / max(1, sum(a for a, _, _ in o))
                L.append(f"| {k} | {cov:.3f} | {y:.3f} | {ser:.3f} | {prec:.3f} |")
                summary[(detector[:6], name, k)] = (cov, y, ser)
            L += ["", "Paired differences, 95% bootstrap CI over items:", ""]
            for a_, b_ in (("gate+plain", "cautious"), ("plain@matched", "cautious"), ("gate+cautious", "cautious"), ("gate+trained", "trained"), ("gate+plain", "trained")):
                for lab, kk, idx in (("SER", 2, list(range(n))), ("yield", 1, ansable)):
                    if not idx:
                        continue
                    mu, lo, hi = boot_diff([sysv[a_][i][kk] for i in idx], [sysv[b_][i][kk] for i in idx], rng)
                    L.append(f"- {a_} minus {b_}, {lab}: {mu:+.3f} [{lo:+.3f}, {hi:+.3f}]")
            L.append("")
    # cross-model: the 4B probe gating the frozen 27B answers on the same 300 SimpleQA-E questions
    big = [json.loads(l) for l in open(BIG, encoding="utf-8")]
    idpos = {e["id"]: i for i, e in enumerate(sa)}
    sc = seg["simpleqa_E"]
    L += ["# Cross-model: 4B evidence probe gating Qwen3.8-27B answers (same 300 questions and passages; repaired grader)", "",
          "| 27B system | coverage | correct | SER | gated coverage | gated correct | gated SER | SER diff [95% CI] | correct diff [95% CI] |", "|---|---|---|---|---|---|---|---|---|"]
    for sname in ("B1_abstain", "B2_strict", "VKG_v2"):
        x = sorted([r for r in big if r["system"] == sname], key=lambda r: idpos[r["id"]])
        assert len(x) == 300
        a = np.array([bool(att(r)) for r in x])
        c = np.array([bool(cor_rep(r)) for r in x]) & a
        e = a & ~c
        gi = np.array([sc[idpos[r["id"]]] > T for r in x])
        ag, cg, eg = a & gi, c & gi, e & gi
        ds = boot_diff(eg, e, rng)
        dc = boot_diff(cg, c, rng)
        L.append(f"| {sname} | {a.mean():.3f} | {c.mean():.3f} | {e.mean():.3f} | {ag.mean():.3f} | {cg.mean():.3f} | {eg.mean():.3f} | {ds[0]:+.3f} [{ds[1]:+.3f}, {ds[2]:+.3f}] | {dc[0]:+.3f} [{dc[1]:+.3f}, {dc[2]:+.3f}] |")
    L.append("")
    # residual analysis: where do the remaining gate+cautious errors on SimpleQA-E come from (passage contains gold or not)?
    R = rows["simpleqa_E"]
    cov_lab = np.array([coverage(e) for e in sa])
    o = [outcome(r, r["cautious"]) for r in R]
    g = seg["simpleqa_E"] > T
    err = np.array([e for _, _, e in o]) & g
    L += ["# Residual errors of gate+cautious on SimpleQA-E (strict detector)", "",
          f"- remaining silent errors: {int(err.sum())}; of these, passage contains the gold answer (string match): {int((err & cov_lab).sum())}; passage does not: {int((err & ~cov_lab).sum())}.",
          f"- probe pass rate among passages without the gold answer: {g[~cov_lab].mean():.3f} ({int(g[~cov_lab].sum())} of {int((~cov_lab).sum())}); among passages with it: {g[cov_lab].mean():.3f}.", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    txt = "\n".join(L)
    (OUT / "S7b_tables.md").write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
