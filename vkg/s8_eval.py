"""S8: apply the code-only answer-vs-passage check (vkg/support_check.py) to frozen outputs.
Sets: DEV = the 300 SimpleQA-E questions (the check was designed after reading 12 residual errors from this set -> not a clean test);
      FRESH = questions 301-500 of the same seed-3000 sample, same retrieval, never inspected before this run (the clean test).
Systems: 4B plain / cautious (S6b prompts; strict UNKNOWN_RE; grade_v3 via probe_eval.correct), 27B B1_abstain / B2_strict (+ VKG_v2 on DEV;
att() and the repaired grader cor_rep, as in freeze 7). A system's answer is kept only if check(...)['ok'].
Run: python -B -m vkg.s8_eval
"""
import json
import re

import numpy as np

from .s6a_clean import is_unknown2

from .analyze_open import att, cor_rep
from .probe_eval import correct
from .probe_gen import ROOT
from .s6b_run import is_unknown
from .support_check import check

S8 = ROOT / "results" / "runs" / "s8"


def non_answer(x):
    """Denial-aware detector plus parse failures: the S6b parser leaves '```json' or a raw '{"answer": ...' string when the JSON did not parse."""
    s = str(x).strip()
    return is_unknown2(s) or s.startswith("```") or s.startswith("{") or bool(re.search(r"\b(passage|text) (does not|doesn't|did not)\b|\bnot (mentioned|provided|stated)\b|\bno (scientific name|answer)\b", s, re.I))


def outcomes_4b(rows, key, detector="strict"):
    isu = is_unknown if detector == "strict" else non_answer
    a = np.array([not isu(r[key]) for r in rows])
    c = np.array([bool(correct({"dataset": "simpleqa", "gold": r["gold"]}, r[key])) for r in rows]) & a
    return a, c, [str(r[key]) for r in rows]


def outcomes_27b(rows):
    a = np.array([bool(att(r)) for r in rows])
    c = np.array([bool(cor_rep(r)) for r in rows]) & a
    return a, c, [r["answer"] for r in rows]


def boot(d, rng, n=2000):
    d = np.asarray(d, float)
    bs = np.sort([rng.choice(d, len(d)).mean() for _ in range(n)])
    return d.mean(), bs[50], bs[1949]


def evaluate(name, items, systems, rng, L, removed_log):
    n = len(items)
    L += [f"## {name} (n={n})", "",
          "| system | coverage | correct | SER | after check: coverage | correct | SER | removed correct | removed wrong | SER diff [95% CI] | correct diff [95% CI] |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    per_test = []
    for sname, (a, c, ans) in systems.items():
        res = [check(it["question"], x, it["passage"]) if ai else None for it, x, ai in zip(items, ans, a)]
        ok = np.array([r["ok"] if r else False for r in res])
        e = a & ~c
        a2, c2, e2 = a & ok, c & ok, e & ok
        ds, dc = boot(e2.astype(float) - e, rng), boot(c2.astype(float) - c, rng)
        L.append(f"| {sname} | {a.mean():.3f} | {c.mean():.3f} | {e.mean():.3f} | {a2.mean():.3f} | {c2.mean():.3f} | {e2.mean():.3f} | "
                 f"{int((c & ~ok).sum())} | {int((e & ~ok).sum())} | {ds[0]:+.3f} [{ds[1]:+.3f}, {ds[2]:+.3f}] | {dc[0]:+.3f} [{dc[1]:+.3f}, {dc[2]:+.3f}] |")
        for t in ("A", "T", "Q"):
            fail = np.array([(r is not None) and not r[t] for r in res])
            per_test.append(f"- {sname}: test {t} rejects {int(fail.sum())} answers ({int((fail & c).sum())} graded correct, {int((fail & e).sum())} graded wrong)")
        for it, x, r, ci in zip(items, ans, res, c):
            if r and not r["ok"]:
                removed_log.append({"set": name, "system": sname, "id": it["id"], "question": it["question"], "gold": it["gold"], "answer": x,
                                    "graded_correct": bool(ci), "failed": r["reason"]})
    L += ["", "Rejections by test (an answer can fail several):", ""] + per_test + [""]


def with_v4(items, sysd):
    """Same answers and abstentions, correctness re-graded with the sensitivity grader v4."""
    from .grade_v4 import correct_v4
    return {k: (a, a & np.array([correct_v4(it["question"], it["gold"], x) for it, x in zip(items, ans)]), ans) for k, (a, c, ans) in sysd.items()}


def main():
    rng = np.random.default_rng(0)
    L = ["# S8: code-only answer-vs-passage check (generated by vkg/s8_eval.py)", "",
         "SER = wrong answers / all questions; correct = correct answers / all questions; graders as in S6b (4B) and freeze 7 (27B). "
         "'removed wrong' are answers the grader marks wrong; some of them may be grader false negatives.", ""]
    removed = []
    # DEV: the 300 SimpleQA-E questions
    ev = [e for e in json.load(open(ROOT / "results" / "runs" / "s6b" / "eval_items.json", encoding="utf-8")) if e["suite"] == "simpleqa_E"]
    o4 = {o["id"]: o for o in map(json.loads, open(ROOT / "results" / "runs" / "s6b" / "eval_outputs.jsonl", encoding="utf-8")) if o["suite"] == "simpleqa_E"}
    rows4 = [o4[e["id"]] for e in ev]
    big = [json.loads(l) for l in open(ROOT / "results" / "runs" / "openworld_simpleqa_hybrid_qwen3.8-27b_s3000_n300.jsonl", encoding="utf-8")]
    sysd = {"4B plain": outcomes_4b(rows4, "plain"), "4B cautious": outcomes_4b(rows4, "cautious"),
            "4B plain (non-answers removed)": outcomes_4b(rows4, "plain", "clean"), "4B cautious (non-answers removed)": outcomes_4b(rows4, "cautious", "clean")}
    for s in ("B1_abstain", "B2_strict", "VKG_v2"):
        b = {r["id"]: r for r in big if r["system"] == s}
        sysd[f"27B {s}"] = outcomes_27b([b[e["id"]] for e in ev])
    evaluate("DEV: SimpleQA-E 300 (check designed after inspecting residuals here; not a clean test)", ev, sysd, rng, L, removed)
    evaluate("DEV, sensitivity: grader v4", ev, with_v4(ev, sysd), rng, L, [])
    # FRESH
    if not ((S8 / "fresh_4b.jsonl").exists() and (S8 / "fresh_27b.jsonl").exists()):
        print("\n".join(L))
        print("(fresh outputs not present: DEV only)")
        return
    fr = json.load(open(S8 / "fresh_items.json", encoding="utf-8"))
    f4 = {o["id"]: o for o in map(json.loads, open(S8 / "fresh_4b.jsonl", encoding="utf-8"))}
    fb = [json.loads(l) for l in open(S8 / "fresh_27b.jsonl", encoding="utf-8")]
    rows4 = [f4[e["id"]] for e in fr]
    sysd = {"4B plain": outcomes_4b(rows4, "plain"), "4B cautious": outcomes_4b(rows4, "cautious"),
            "4B plain (non-answers removed)": outcomes_4b(rows4, "plain", "clean"), "4B cautious (non-answers removed)": outcomes_4b(rows4, "cautious", "clean")}
    for s in ("B1_abstain", "B2_strict"):
        b = {r["id"]: r for r in fb if r["system"] == s}
        sysd[f"27B {s}"] = outcomes_27b([b[e["id"]] for e in fr])
    evaluate("FRESH: SimpleQA questions 301-500, same retrieval (clean test)", fr, sysd, rng, L, removed)
    evaluate("FRESH, sensitivity: grader v4 (rules designed on earlier rows; out of sample here)", fr, with_v4(fr, sysd), rng, L, [])
    txt = "\n".join(L)
    (S8 / "S8_tables.md").write_text(txt, encoding="utf-8")
    with open(S8 / "removed_answers.jsonl", "w", encoding="utf-8") as f:
        for r in removed:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(txt)


if __name__ == "__main__":
    main()
